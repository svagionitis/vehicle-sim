#pragma once

#include <cmath>

#include "libs/VehicleSimCore/dynamics/IVehicleDynamics.h"
#include "libs/VehicleSimCore/math/Vec2.h"

namespace vehicle_sim::physics {
class RigidBody2D;
} // namespace vehicle_sim::physics

namespace vehicle_sim::dynamics {

/// @struct AntiGravityConfig
/// @brief Configuration parameters for futuristic anti-gravity maglev racer dynamics.
/// @details Defines magnetic levitation ride height, spring/damper suspension,
/// propulsion thrust, turbo boost, independent differential airbrakes, and lateral drift slip.
struct AntiGravityConfig {
    double mass { 1050.0 }; ///< Racer structural mass in kg.
    double length { 4.8 }; ///< Vehicle chassis length in meters.
    double width { 2.4 }; ///< Vehicle chassis width in meters.

    double targetRideHeight { 1.2 }; ///< Equilibrium magnetic levitation altitude in meters.
    double maxLevitationRange { 2.6 }; ///< Altitude boundary beyond which magnetic lock decouples in meters.
    double suspensionStiffness { 92000.0 }; ///< Maglev vertical repulsion spring rate in N/m.
    double suspensionDamping { 8200.0 }; ///< Maglev vertical oscillation damper rate in N*s/m.

    double maxForwardThrust { 42000.0 }; ///< Peak ion engine propulsion force in Newtons.
    double maxReverseThrust { 16000.0 }; ///< Peak reverse braking thruster force in Newtons.
    double boostMultiplier { 1.8 }; ///< Thrust multiplier when boost capacitor is discharged.
    double maxBoostEnergy { 3.5 }; ///< Total boost reservoir capacity in seconds.
    double boostRechargeRate { 0.5 }; ///< Boost capacitor replenishment rate in seconds per second.

    double steerTorque { 32000.0 }; ///< Primary fly-by-wire yaw steering moment in N*m.
    double airbrakeDragCoeff { 190.0 }; ///< Retardation force coefficient per airbrake flap in N/(m/s)^2.
    double airbrakeYawTorque { 26000.0 }; ///< Differential yaw steering torque generated by airbrake deployment in N*m.

    double lateralGripStiffness { 28000.0 }; ///< Lateral magnetic guide rail traction stiffness in N*s/m.
    double driftThreshold { 6.5 }; ///< Lateral slip speed threshold initiating slipstream drift in m/s.
    double linearDragCoeff { 0.42 }; ///< Baseline subsonic aerodynamic drag coefficient.
    double supersonicThreshold { 120.0 }; ///< Speed threshold where transonic shockwave drag steepens in m/s.
    double supersonicDragMult { 3.2 }; ///< Supersonic compressibility drag multiplier.

    double bankingCoupling { 0.02 }; ///< Roll banking angle proportionality factor in rad/(rad/s).
    double angularDamping { 6500.0 }; ///< Yaw angular velocity damping moment in N*m*s.
    math::Vec2 gravity { 0.0, -9.80665 }; ///< Ambient gravity acceleration vector in m/s^2.
};

/// @struct AntiGravityInput
/// @brief Pilot control inputs for anti-gravity maglev racer dynamics.
struct AntiGravityInput {
    double throttle { 0.0 }; ///< Commanded propulsion throttle in [-1.0, 1.0].
    double steer { 0.0 }; ///< Commanded directional yaw steering in [-1.0, 1.0].
    double leftAirbrake { 0.0 }; ///< Left airbrake flap deployment in [0.0, 1.0].
    double rightAirbrake { 0.0 }; ///< Right airbrake flap deployment in [0.0, 1.0].
    bool boost { false }; ///< Boost capacitor discharge trigger.
    double trackDistance { 1.2 }; ///< Measured vertical distance to track surface in meters.
};

/// @struct AntiGravityTelemetry
/// @brief Diagnostic snapshot of anti-gravity racer dynamics states.
struct AntiGravityTelemetry {
    double speed { 0.0 }; ///< Absolute velocity magnitude in m/s.
    double forwardSpeed { 0.0 }; ///< Longitudinal velocity along vehicle heading in m/s.
    double lateralSpeed { 0.0 }; ///< Transverse velocity across vehicle beam in m/s.
    double rideHeight { 0.0 }; ///< Current track separation distance in meters.
    double suspensionForce { 0.0 }; ///< Total upward magnetic levitation force in Newtons.
    double thrustForce { 0.0 }; ///< Active ion engine thrust in Newtons.
    double airbrakeDrag { 0.0 }; ///< Total aerodynamic drag from deployed airbrakes in Newtons.
    double netYawTorque { 0.0 }; ///< Combined steering and airbrake yaw torque in N*m.
    double bankAngle { 0.0 }; ///< Roll banking angle into turn in radians.
    double boostEnergy { 0.0 }; ///< Remaining boost capacitor energy in seconds.
    bool isBoostActive { false }; ///< True if boost is actively firing.
    bool isLevitating { true }; ///< True if craft is magnetically locked to the track.
    bool isDrifting { false }; ///< True if lateral slip exceeds drift threshold.
};

/// @class AntiGravityRacerDynamics
/// @brief 2D futuristic anti-gravity maglev racer dynamics coordinator.
/// @details Simulates magnetic levitation repulsion and damping, ion propulsion with capacitor boost,
/// independent left/right airbrakes inducing differential yaw torque, supersonic wave drag,
/// dynamic roll banking, and high-speed drift physics.
class AntiGravityRacerDynamics final : public IVehicleDynamics {
public:
    /// @brief Default constructor using baseline anti-gravity configuration.
    AntiGravityRacerDynamics() noexcept;

    /// @brief Parameterized constructor with custom anti-gravity configuration.
    /// @param[in] config Anti-gravity racer configuration parameters.
    explicit AntiGravityRacerDynamics(const AntiGravityConfig& config) noexcept;

    /// @brief Advances anti-gravity simulation step by timestep dt.
    /// @details Computes magnetic levitation force, propulsion thrust, differential airbrakes,
    /// lateral grip/drift forces, applies forces to rigid body, and updates capacitor charge.
    /// @param[in,out] body Target rigid body receiving forces and moments.
    /// @param[in] dt Timestep duration in seconds.
    void step(physics::RigidBody2D& body, double dt) noexcept override;

    /// @brief Resets transient control inputs, boost energy, and flight states.
    void reset() noexcept override;

    /// @brief Queries whether the racer is decoupled from the track (in ballistic flight).
    /// @return True if craft is detached from magnetic levitation range.
    [[nodiscard]] bool isAirborne() const noexcept override;

    /// @brief Gets active anti-gravity racer configuration.
    /// @return Const reference to active AntiGravityConfig.
    [[nodiscard]] const AntiGravityConfig& getConfig() const noexcept;

    /// @brief Updates active anti-gravity configuration.
    /// @param[in] config New configuration parameters.
    void setConfig(const AntiGravityConfig& config) noexcept;

    /// @brief Gets current pilot control inputs.
    /// @return Const reference to active AntiGravityInput.
    [[nodiscard]] const AntiGravityInput& getInput() const noexcept;

    /// @brief Sets pilot control inputs.
    /// @param[in] input New pilot control commands.
    void setInput(const AntiGravityInput& input) noexcept;

    /// @brief Gets diagnostic telemetry snapshot.
    /// @return Const reference to AntiGravityTelemetry.
    [[nodiscard]] const AntiGravityTelemetry& getTelemetry() const noexcept;

    /// @brief Queries whether the craft is magnetically locked to the track.
    /// @return True if within active levitation range.
    [[nodiscard]] bool isLevitating() const noexcept;

    /// @brief Queries whether boost thrust is actively firing.
    /// @return True if boost capacitor is discharging.
    [[nodiscard]] bool isBoostActive() const noexcept;

    /// @brief Queries whether the craft is in a high-slip drift state.
    /// @return True if lateral slip velocity exceeds drift threshold.
    [[nodiscard]] bool isDrifting() const noexcept;

    /// @brief Gets current ride height above the track surface in meters.
    /// @return Distance in meters.
    [[nodiscard]] double getRideHeight() const noexcept;

    /// @brief Gets current roll banking angle in radians.
    /// @return Bank angle in radians.
    [[nodiscard]] double getBankAngle() const noexcept;

    /// @brief Gets current forward speed along vehicle heading.
    /// @return Speed in m/s.
    [[nodiscard]] double getSpeed() const noexcept;

    /// @brief Gets remaining boost energy in seconds.
    /// @return Energy reserve in seconds.
    [[nodiscard]] double getBoostEnergy() const noexcept;

private:
    AntiGravityConfig mConfig { };
    AntiGravityInput mInput { };
    AntiGravityTelemetry mTelemetry { };
    double mBoostEnergy { 0.0 };
};

} // namespace vehicle_sim::dynamics
