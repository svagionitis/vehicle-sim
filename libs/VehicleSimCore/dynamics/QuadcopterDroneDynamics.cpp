#include "libs/VehicleSimCore/dynamics/QuadcopterDroneDynamics.h"

#include <algorithm>
#include <cmath>

#include "libs/VehicleSimCore/physics/RigidBody2D.h"

namespace vehicle_sim::dynamics {

QuadcopterDroneDynamics::QuadcopterDroneDynamics() noexcept
    : QuadcopterDroneDynamics(QuadcopterConfig {})
{
}

QuadcopterDroneDynamics::QuadcopterDroneDynamics(const QuadcopterConfig& config) noexcept
    : mConfig { config }
    , mPitchController { config.pitchGains }
{
}

void QuadcopterDroneDynamics::reset() noexcept
{
    mPitchController.reset();
    for (auto& speed : mMotorSpeeds) {
        speed = 0.0;
    }
    for (auto& target : mTargetSpeeds) {
        target = 0.0;
    }
    mThrottle = 0.0;
    mTargetPitch = 0.0;
    mTotalThrust = 0.0;
    mYawTorque = 0.0;
    mArmed = false;
    mIsAirborne = false;
}

bool QuadcopterDroneDynamics::isAirborne() const noexcept
{
    return mIsAirborne && mArmed;
}

void QuadcopterDroneDynamics::setThrottle(double throttle) noexcept
{
    mThrottle = std::clamp(throttle, 0.0, 1.0);
}

void QuadcopterDroneDynamics::setPitchAngle(double pitch) noexcept
{
    mTargetPitch = std::clamp(pitch, -0.78, 0.78); // Clamped to +/- 45 degrees
}

void QuadcopterDroneDynamics::setArmed(bool armed) noexcept
{
    mArmed = armed;
    if (!mArmed) {
        for (auto& target : mTargetSpeeds) {
            target = 0.0;
        }
    }
}

const std::array<double, 4>& QuadcopterDroneDynamics::getMotorSpeeds() const noexcept
{
    return mMotorSpeeds;
}

double QuadcopterDroneDynamics::getTotalThrust() const noexcept
{
    return mTotalThrust;
}

double QuadcopterDroneDynamics::getYawTorque() const noexcept
{
    return mYawTorque;
}

const QuadcopterConfig& QuadcopterDroneDynamics::getConfig() const noexcept
{
    return mConfig;
}

void QuadcopterDroneDynamics::evaluateMixer(double collectiveThrottle, double pitchCommand) noexcept
{
    if (!mArmed) {
        for (auto& target : mTargetSpeeds) {
            target = 0.0;
        }
        return;
    }

    // Idle motor speed when armed
    const double idleSpeed { mConfig.maxMotorSpeed * 0.12 };
    const double baseSpeed { idleSpeed + collectiveThrottle * (mConfig.maxMotorSpeed - idleSpeed) };

    // Pitch differential speed (+pitch command raises rear motors 2 & 3, lowers front 0 & 1)
    const double pitchDelta { pitchCommand * 450.0 };

    mTargetSpeeds[0] = std::clamp(baseSpeed - pitchDelta, 0.0, mConfig.maxMotorSpeed);
    mTargetSpeeds[1] = std::clamp(baseSpeed - pitchDelta, 0.0, mConfig.maxMotorSpeed);
    mTargetSpeeds[2] = std::clamp(baseSpeed + pitchDelta, 0.0, mConfig.maxMotorSpeed);
    mTargetSpeeds[3] = std::clamp(baseSpeed + pitchDelta, 0.0, mConfig.maxMotorSpeed);
}

void QuadcopterDroneDynamics::updateMotorSpeeds(double dt) noexcept
{
    const double tau { std::max(1e-4, mConfig.motorTimeConstant) };
    const double alpha { std::clamp(dt / tau, 0.0, 1.0) };

    for (std::size_t i { 0 }; i < 4; ++i) {
        mMotorSpeeds[i] += alpha * (mTargetSpeeds[i] - mMotorSpeeds[i]);
    }
}

void QuadcopterDroneDynamics::step(physics::RigidBody2D& body, double dt) noexcept
{
    if (dt <= 0.0) {
        return;
    }

    // Evaluate closed-loop pitch attitude feedback
    const double currentPitch { body.getOrientation() };
    const double pitchEffort { mPitchController.update(mTargetPitch, currentPitch, dt) };

    evaluateMixer(mThrottle, pitchEffort);
    updateMotorSpeeds(dt);

    // Compute individual rotor thrusts and drag torques
    // 0: FL (CW), 1: FR (CCW), 2: RL (CCW), 3: RR (CW)
    std::array<double, 4> thrusts {};
    std::array<double, 4> torques {};

    double sumThrust { 0.0 };
    for (std::size_t i { 0 }; i < 4; ++i) {
        const double omega { mMotorSpeeds[i] };
        thrusts[i] = mConfig.thrustCoeff * (omega * omega);
        torques[i] = mConfig.torqueCoeff * (omega * omega);
        sumThrust += thrusts[i];
    }
    mTotalThrust = sumThrust;

    // Yaw reactionary torque: CW (0, 3) vs CCW (1, 2)
    mYawTorque = (torques[0] + torques[3]) - (torques[1] + torques[2]);

    // Pitch moment generated by front (0, 1) vs rear (2, 3) thrust differential
    constexpr double invSqrt2 { 0.7071067811865475 };
    const double pitchArm { mConfig.armLength * invSqrt2 };
    const double pitchTorque { pitchArm * ((thrusts[2] + thrusts[3]) - (thrusts[0] + thrusts[1])) };

    // Air resistance damping
    const math::Vec2 worldVel { body.getLinearVelocity() };
    const double speedSqr { worldVel.lengthSquared() };
    const double speed { std::sqrt(speedSqr) };
    math::Vec2 dragForce { 0.0, 0.0 };
    if (speed > 1e-3) {
        dragForce = worldVel * (-mConfig.linearDragCoeff * speed);
    }

    const double angularDampTorque { -mConfig.angularDamping * body.getAngularVelocity() };

    // Thrust vector in body-local frame points along +Y (upward through drone roof)
    const math::Vec2 thrustLocal { 0.0, mTotalThrust };
    const math::Vec2 thrustWorld { body.toWorldVec(thrustLocal) };

    // Net forces dispatched to rigid body
    body.applyForce(thrustWorld + dragForce);
    body.applyTorque(pitchTorque + angularDampTorque);

    // Airborne state detection
    constexpr double gravityConst { 9.81 };
    const double hoverThrust { mConfig.mass * gravityConst };
    mIsAirborne = (mTotalThrust > hoverThrust * 0.4) && (body.getPosition().y > 0.05);
}

} // namespace vehicle_sim::dynamics
